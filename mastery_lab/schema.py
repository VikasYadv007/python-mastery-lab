"""Shared additive schema. PostgreSQL differs only in its attempt ID syntax.

Never remove tables here when upgrading an existing learner database.
"""

SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    profile TEXT NOT NULL,
    kind TEXT NOT NULL,
    configuration TEXT NOT NULL,
    queue TEXT NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    completed_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_profile ON sessions(profile,kind,created_at);
CREATE TABLE IF NOT EXISTS attempts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    profile TEXT NOT NULL,
    session_id TEXT NOT NULL,
    question_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    answer_index INTEGER,
    correct INTEGER NOT NULL,
    response_text TEXT,
    created_at TEXT NOT NULL,
    UNIQUE(profile, session_id, question_id)
);
CREATE INDEX IF NOT EXISTS idx_attempt_profile ON attempts(profile,created_at);
CREATE TABLE IF NOT EXISTS mastery (
    profile TEXT NOT NULL,
    question_id TEXT NOT NULL,
    streak INTEGER NOT NULL DEFAULT 0,
    total_correct INTEGER NOT NULL DEFAULT 0,
    total_wrong INTEGER NOT NULL DEFAULT 0,
    last_correct INTEGER,
    next_due TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY(profile, question_id)
);
CREATE TABLE IF NOT EXISTS bookmarks (
    profile TEXT NOT NULL,
    question_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY(profile,question_id)
);
CREATE TABLE IF NOT EXISTS personal_notes (
    profile TEXT NOT NULL,
    question_id TEXT NOT NULL,
    note TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY(profile,question_id)
);
CREATE TABLE IF NOT EXISTS code_drafts (
    profile TEXT NOT NULL,
    question_id TEXT NOT NULL,
    code TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY(profile,question_id)
);
CREATE TABLE IF NOT EXISTS users (
    username TEXT PRIMARY KEY,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS uploaded_packs (
    pack_id TEXT PRIMARY KEY,
    body TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL);
"""

PG_SCHEMA = SQLITE_SCHEMA.replace(
    "id INTEGER PRIMARY KEY AUTOINCREMENT",
    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
)
