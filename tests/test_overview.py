"""Overview data stays accurate and imported names never become executable code."""

import json
import re
from html.parser import HTMLParser

from mastery_lab.overview import ASSETS, observatory_html, topic_summaries
from ui_style import CSS, THEMES


class SceneParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.payload = None
        self.images = []
        self.scripts = []
        self.in_script = False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get("id") == "python-observatory":
            self.payload = json.loads(attrs["data-info"])
        if tag == "img":
            self.images.append(attrs)
        if tag == "script":
            self.in_script = True

    def handle_endtag(self, tag):
        if tag == "script":
            self.in_script = False

    def handle_data(self, data):
        if self.in_script:
            self.scripts.append(data)


def test_scene_keeps_imported_names_out_of_executable_source():
    name = '</script><script>window.hacked=1</script>__OV_SCRIPT__"&'
    summary = {"mcqs": 0, "coding": 0, "studied": 0, "accuracy": None, "streak": 0, "due": 0}
    scene = observatory_html(summary, [{"name": name}], dark=True)
    parser = SceneParser()
    parser.feed(scene)
    assert parser.payload["topics"][0]["name"] == name
    assert "".join(parser.scripts) == ASSETS.joinpath("overview.js").read_text(encoding="utf-8")
    assert "window.hacked" not in "".join(parser.scripts)
    assert parser.images[0]["src"].startswith("data:image/svg+xml;base64,")


def test_topic_coverage_is_not_confused_with_accuracy_or_mastery():
    pack = {
        "pack_id": "one",
        "title": "Lecture",
        "topics": [{"id": "types", "name": "Types"}],
        "questions": [{"id": "m1", "type": "mcq", "topic": "types"}],
        "challenges": [{"id": "c1", "type": "coding", "topic": "types"}],
    }
    mastery = {
        "m1": {"total_correct": 3, "total_wrong": 1, "last_correct": 1, "streak": 3},
        "c1": {"total_correct": 0, "total_wrong": 2, "last_correct": 0, "streak": 0},
        "missing": {"total_correct": 100, "total_wrong": 0, "last_correct": 1, "streak": 100},
    }
    row = topic_summaries({"one": pack}, mastery)[0]
    assert row["studied"] == row["questions"] == 2
    assert row["accuracy"] == 50
    assert row["mastered"] == row["missed"] == 1
    assert row["mcqs"] == row["coding"] == 1


def test_empty_topics_do_not_invent_accuracy():
    assert topic_summaries({}, {}) == []
    pack = {"pack_id": "one", "title": "Lecture", "topics": [{"id": "types", "name": "Types"}]}
    row = topic_summaries({"one": pack}, {})[0]
    assert row["accuracy"] is None
    assert row["questions"] == row["studied"] == 0


def test_shared_styles_have_complete_theme_tokens_including_numbered_surfaces():
    consumed = set(re.findall(r"var\((--[a-zA-Z0-9_-]+)", CSS))
    # Icon is generated by style(); the coverage ring supplies its offset inline.
    local = {"--theme-icon", "--ring-offset"}
    for tokens in THEMES.values():
        assert not consumed - tokens.keys() - local
